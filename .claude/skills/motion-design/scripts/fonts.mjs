#!/usr/bin/env node
// fonts.mjs — bundle open-licensed fonts into the film so renders never depend on system fonts.
// Fonts come from the npm registry (@fontsource packages, OFL/Apache), fetched with `npm pack`,
// so whatever proxy/registry npm is configured with also works here.
//
//   node tools/fonts.mjs add "Space Grotesk" 500,700            static weights (latin + latin-ext)
//   node tools/fonts.mjs add Inter 400,600,800 --subsets latin,cyrillic
//   node tools/fonts.mjs add "Inter" --variable                  variable font (animate weight with font-variation-settings)
//   node tools/fonts.mjs add "Instrument Serif" 400 --italic
//   node tools/fonts.mjs list
//
// Writes assets/fonts/<id>/*.woff2 + LICENSE, regenerates assets/fonts/fonts.css and adds a
// face per weight to film.json "fonts", which mount() loads and verifies before frame 0.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const argv = process.argv.slice(2);
const flags = {}, pos = [];
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a.startsWith('--')) { const n = argv[i + 1]; if (n && !n.startsWith('--')) { flags[a.slice(2)] = n; i++; } else flags[a.slice(2)] = true; }
  else pos.push(a);
}
const DIR = path.resolve(flags.dir || process.cwd());
const FONTS = path.join(DIR, 'assets', 'fonts');
const MANIFEST = path.join(FONTS, 'fonts.json');
const die = (m) => { console.error('✗ ' + m); process.exit(1); };

const readManifest = () => (fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : { faces: [] });

function writeCss(man) {
  const css = man.faces.map((f) => `@font-face {\n  font-family: "${f.family}";\n  src: url("${f.file}") format("woff2");\n  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: block;${f.unicodeRange ? `\n  unicode-range: ${f.unicodeRange};` : ''}\n}`).join('\n\n');
  fs.writeFileSync(path.join(FONTS, 'fonts.css'), `/* generated by tools/fonts.mjs — do not edit by hand */\n${css}\n`);
}

function addToFilmJson(specs) {
  const fj = path.join(DIR, 'film.json');
  if (!fs.existsSync(fj)) return;
  const film = JSON.parse(fs.readFileSync(fj, 'utf8'));
  film.fonts = film.fonts || [];
  for (const s of specs) if (!film.fonts.includes(s)) film.fonts.push(s);
  fs.writeFileSync(fj, JSON.stringify(film, null, 2) + '\n');
}

function add() {
  const family = pos[1];
  if (!family) die('usage: add "<Family Name>" [weights] [--subsets latin,cyrillic] [--italic] [--variable]');
  const id = family.toLowerCase().trim().replace(/\s+/g, '-');
  const variable = !!flags.variable;
  const pkg = `@fontsource${variable ? '-variable' : ''}/${id}`;
  const weights = variable ? [] : String(pos[2] || '400,700').split(',').map((w) => w.trim());
  const subsets = String(flags.subsets || 'latin,latin-ext').split(',').map((s) => s.trim());
  const style = flags.italic ? 'italic' : 'normal';
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mg-fonts-'));
  console.log(`fetching ${pkg} from npm…`);
  const r = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['pack', pkg, '--pack-destination', tmp, '--silent'], { encoding: 'utf8', shell: process.platform === 'win32' });
  if (r.status !== 0) die(`npm pack ${pkg} failed — check the family name at https://fontsource.org (e.g. "Space Grotesk", "Inter", "Unbounded").\n${r.stderr || r.stdout}`);
  const tgz = fs.readdirSync(tmp).find((f) => f.endsWith('.tgz'));
  const x = spawnSync('tar', ['-xzf', path.join(tmp, tgz), '-C', tmp]);
  if (x.status !== 0) die('could not extract ' + tgz);
  const root = path.join(tmp, 'package');
  const meta = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const unicode = fs.existsSync(path.join(root, 'unicode.json')) ? JSON.parse(fs.readFileSync(path.join(root, 'unicode.json'), 'utf8')) : {};
  const files = fs.readdirSync(path.join(root, 'files')).filter((f) => f.endsWith('.woff2'));
  const dest = path.join(FONTS, id);
  fs.mkdirSync(dest, { recursive: true });
  for (const lic of ['LICENSE', 'LICENSE.md', 'OFL.txt']) if (fs.existsSync(path.join(root, lic))) fs.copyFileSync(path.join(root, lic), path.join(dest, 'LICENSE'));
  const man = readManifest();
  const famName = variable ? `${family} Variable` : family;
  man.faces = man.faces.filter((f) => !(f.family === famName && (variable || weights.includes(String(f.weight))) && f.style === style));
  const added = [], specs = [];
  for (const sub of subsets) {
    const want = variable
      ? files.filter((f) => f.startsWith(`${id}-${sub}-`) && f.endsWith(`-${style}.woff2`) && /-(wght|standard|full)-/.test(f))
      : weights.map((w) => `${id}-${sub}-${w}-${style}.woff2`).filter((f) => files.includes(f));
    if (!want.length) { console.log(`  (no ${sub} files for ${style}${variable ? ' variable' : ' ' + weights.join(',')})`); continue; }
    const pick = variable ? [want.find((f) => f.includes('-wght-')) || want[0]] : want;
    for (const f of pick) {
      fs.copyFileSync(path.join(root, 'files', f), path.join(dest, f));
      const w = variable ? '100 900' : f.split('-').slice(-2)[0];
      man.faces.push({ family: famName, weight: w, style, file: `${id}/${f}`, subset: sub, unicodeRange: unicode[sub] || null, license: meta.license || 'see LICENSE', source: `${pkg}@${meta.version}` });
      added.push(f);
    }
  }
  if (!added.length) die(`nothing matched. Available files: ${files.slice(0, 12).join(', ')}…`);
  man.faces.sort((a, b) => (a.family + a.weight + a.subset).localeCompare(b.family + b.weight + b.subset));
  fs.writeFileSync(MANIFEST, JSON.stringify(man, null, 2) + '\n');
  writeCss(man);
  for (const w of variable ? ['400'] : weights) specs.push(`${style === 'italic' ? 'italic ' : ''}${w} 64px "${famName}"`);
  addToFilmJson(specs);
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`✓ ${famName} (${meta.license || 'license in LICENSE'}): ${added.length} file(s) → assets/fonts/${id}/`);
  console.log(`  use: font-family: "${famName}"${variable ? '; animate with font-variation-settings: "wght" 100…900' : ''}`);
  console.log(`  film.json "fonts" now verifies: ${specs.join(', ')}`);
}

function list() {
  const man = readManifest();
  if (!man.faces.length) return console.log('no bundled fonts yet — add one with: node tools/fonts.mjs add "Inter" 400,700');
  for (const f of man.faces) console.log(`${f.family} ${f.weight} ${f.style} [${f.subset}] ${f.file} (${f.license})`);
}

if (pos[0] === 'add') add();
else if (pos[0] === 'list') list();
else console.log(fs.readFileSync(new URL(import.meta.url), 'utf8').split('\n').slice(1, 14).join('\n').replace(/^\/\/ ?/gm, ''));
